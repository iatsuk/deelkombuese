function graphGroup(product) {
  if (product.category === 'Крупы и основы' || product.id === 'potato') return 'bases';
  if (['Белок и бобовые', 'Яйца', 'С берега'].includes(product.category)) return 'protein';
  if (['Хлеб и булочки', 'Молоко и добавки'].includes(product.category)) return 'bread-dairy';
  if (
    [
      'garlic',
      'driedGarlic',
      'ginger',
      'driedGinger',
      'aromatics',
      'herbs',
      'chili',
      'curry',
      'cumin',
      'paprika',
      'salt',
      'pepper',
      'bouillon',
    ].includes(product.id)
  )
    return 'spices';
  if (['Свежие овощи', 'Овощные консервы', 'Сушёные овощи'].includes(product.category))
    return 'vegetables';
  if (
    ['tomatoPaste', 'passata', 'ketchup', 'pesto', 'coconut', 'oil', 'peanutButter'].includes(
      product.id,
    )
  )
    return 'sauces';
  return 'other';
}
