import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
export function generateOfflineAssets() {
  const walk = (directory) =>
    readdirSync(directory, { withFileTypes: true }).flatMap((entry) =>
      entry.isDirectory() ? walk(directory + '/' + entry.name) : [directory + '/' + entry.name],
    );
  const files = [
    'index.html',
    'favicon.svg',
    'manifest.webmanifest',
    'site-analytics.js',
    'theme-preference.js',
    ...['src', 'fonts', 'assets', 'locales', 'impressum', 'datenschutz'].flatMap(walk),
    // The chapter pages in every language; dish, recipe and product pages are cached when
    // visited, and offline the app root opens on their view.
    ...['generators', 'en/generators', 'de/generators']
      .filter(existsSync)
      .flatMap(walk)
      .filter((file) => /^(?:(?:en|de)\/)?generators\/(?:[^/]+\/)?index\.html$/.test(file)),
  ].filter(existsSync);
  const hash = createHash('sha256');
  for (const file of files.sort()) {
    hash.update(file);
    hash.update(readFileSync(file));
  }
  writeFileSync(
    'offline-assets.js',
    `// Generated by scripts/offline-assets.mjs; do not edit by hand.\nself.KAMBUZ_CACHE_NAME='kombuese-${hash.digest('hex').slice(0, 16)}';\nself.KAMBUZ_OFFLINE_ASSETS=${JSON.stringify(['./', ...files.map((file) => './' + file)])};\n`,
  );
}
if (process.argv[1]?.endsWith('offline-assets.mjs')) generateOfflineAssets();
